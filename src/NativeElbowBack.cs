    public static void Sample(float bend, bool left, out Vector3 offset, out float angle)
    {
        var table = left ? ElboBackL : ElboBackR;
        if (bend <= 0f) { offset = Vector3.zero; angle = 0f; return; }
        int lo = 0, hi = table.GetLength(0) - 1;
        if (bend >= table[hi, 0]) lo = hi;
        else while (hi - lo > 1)
        {
            int mid = (lo + hi) / 2;
            if (table[mid, 0] <= bend) lo = mid; else hi = mid;
        }
        float t = lo == hi ? 0f : (bend - table[lo, 0]) / (table[hi, 0] - table[lo, 0]);
        float x = table[lo, 1] + t * (table[hi, 1] - table[lo, 1]);
        float z = table[lo, 2] + t * (table[hi, 2] - table[lo, 2]);
        angle = table[lo, 3] + t * (table[hi, 3] - table[lo, 3]) - table[0, 3];
        offset = new Vector3(x - table[0, 1], 0f, z - table[0, 2]);
    }

